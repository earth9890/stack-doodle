#!/usr/bin/env python3
"""Make an episode's logo assets from simple-icons (CC0 artwork; the marks stay their owners' trademarks).

usage: python3 tools/logos.py OUT.js NAME [NAME ...]      e.g. tools/logos.py episodes/01-bun/assets/logos.js bun node.js deno
Writes L.reg("logo", "logo-<slug>") assets; in scenes.js put `// @include assets/logos.js` AFTER `// @library auto`, then
L.put(S, "logo-bun", x, y, { s: 1, t, tile: true, label: true }).  Nominative use only: show a product's mark when the
video talks about that product, never edited, mocked into a new mark, or used in our own branding.
Names match slug, title or alias (case-insensitive). A brand simple-icons dropped (OpenAI, Microsoft, AWS …) prints MISSING:
show its name as text instead.
"""
import utils.transport
import utils.session
import json, pathlib, re, sys, urllib.request

VER = '16.34.0'  # pinned: published 2026-10-04
CDN = f'https://cdn.jsdelivr.net/npm/simple-icons@{VER}'
CACHE = pathlib.Path(__file__).resolve().parent / '.cache'


def get(url, path):
    if not path.exists():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(urllib.request.urlopen(url, timeout=30).read())
    return path.read_text()


def find(data, name):
    n = name.lower().strip()
    for icon in data:
        aka = re.findall(r'"(?:title"\s*:\s*")?([^"]+)"', json.dumps(icon.get('aliases') or {}))  # aka list, loc names, dup titles
        if n in (icon['slug'], icon['title'].lower(), *(a.lower() for a in aka)):
            return icon


def main(out, names):
    data = json.loads(get(f'{CDN}/data/simple-icons.json', CACHE / f'simple-icons-{VER}.json'))
    logos, missing = {}, []
    for name in names:
        icon = find(data, name)
        if not icon:
            missing.append(name)
            continue
        svg = get(f'{CDN}/icons/{icon["slug"]}.svg', CACHE / VER / f'{icon["slug"]}.svg')
        logos[icon['slug']] = {'title': icon['title'], 'hex': '#' + icon['hex'], 'd': re.search(r' d="([^"]+)"', svg)[1]}
    js = f'''// generated by tools/logos.py from simple-icons {VER} (CC0 artwork; marks are their owners' trademarks; nominative use only)
(function () {{
const L = window.L;
const LOGOS = {json.dumps(logos, indent=0)};
// brand colour as given; near-black marks turn white on a dark tile
const lum = (h) => [1, 3, 5].map((i) => parseInt(h.slice(i, i + 2), 16) / 255).reduce((a, v, i) => a + v * [0.2126, 0.7152, 0.0722][i], 0);
for (const [slug, v] of Object.entries(LOGOS))
  L.reg("logo", "logo-" + slug, (o) => {{
    const dark = o.tile === "dark", fill = o.mono ? L.c(o.mono) : dark && lum(v.hex) < 0.25 ? "#ffffff" : v.hex;
    const tile = o.tile ? L.shape(L.rrect(-70, -70, 140, 140, 28), dark ? "navy" : "white", {{ w: "prop" }}) : "";
    const mark = `<path d="${{v.d}}" fill="${{fill}}" transform="translate(-48 -48) scale(4)"/>`;
    const label = o.label ? L.text(o.label === true ? v.title : o.label, 0, o.tile ? 130 : 105, {{ size: 44, c: o.labelC || "ink" }}) : "";
    return tile + mark + label;
  }}, {{ box: [-110, -110, 220, 270], group: "Logos", label: v.title, tags: [slug, v.title.toLowerCase(), "logo", "brand"],
    call: `L.put(S, "logo-${{slug}}", x, y, {{ s: 1, t, tile: true|"dark", label: true, labelC: "white", mono }})`, demo: {{ tile: true, label: true }} }});
}})();
'''
    pathlib.Path(out).parent.mkdir(parents=True, exist_ok=True)
    pathlib.Path(out).write_text(js)
    print(f'{out}: {", ".join(logos) or "none"}' + (f'\nMISSING (show the name as text): {", ".join(missing)}' if missing else ''))


if __name__ == '__main__':
    if len(sys.argv) < 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2:])
